/// The Guide tab: titled sections of short paragraphs.
pub(crate) fn guide(browser: bool) -> Vec<(&'static str, Vec<&'static str>)> {
    let sources = if browser {
        vec![
            "Native and web share the same Rust/GPUI UI foundation and required Python adapter for Live and Replay.",
            "Use the sidebar Configure session controls to connect Live or replay a ZView recording with its matching ELF or build. File paths are local to the adapter and constrained by its data root.",
            "Start the browser through just web-gui, zview-gui, or west zview-gui. An unavailable adapter is reported in the UI and retried; session controls remain accessible.",
        ]
    } else {
        vec![
            "Native and web share the same Rust/GPUI UI foundation, Python adapter, and sidebar Configure session controls for Live and Replay. Select the adapter environment with --python or ZVIEW_GUI_PYTHON.",
            "The Python adapter is required by default. Replay reads recordings generated by ZView and needs their matching ELF or build. Missing adapter dependencies are reported as errors.",
            "Launch with --rust-core for experimental Replay and trusted loopback GDB Live without Python. Enter local file paths and the matching ELF directly; Live polls a fixed inventory without heap maps.",
            "Use Configure session to open a recording through Replay. Disconnect stops Live acquisition; Stop decoding stops replay decoding. An externally managed adapter is not stopped when this window closes.",
        ]
    };
    vec![
        ("Data sources", sources),
        (
            "Navigation",
            vec![
                "Click a thread row to open details. Escape or Back to Overview returns without changing session time.",
                "Expand Kernel objects in the sidebar to filter by type; search filters by name/address. Escape and Back return with filters intact.",
                "Breadcrumbs open their named list with search cleared; Kernel objects shows all types. Previous/Next changes the shared snapshot.",
            ],
        ),
        (
            "Reading the views",
            vec![
                "CPU excludes idle. Stack watermark is not total device RAM. Options are raw target flags.",
                "Histories show sampled counts/depth, not individual operations. State bars show counts, occupancy, or lock/busy state—not CPU usage.",
                "Unknown wait queues are labelled unavailable; known empty queues are blank.",
                "Heap maps show captured chunks and relative offsets, not absolute block addresses.",
            ],
        ),
    ]
}

/// The Guide as plain text, for tests.
#[cfg(test)]
pub(crate) fn help_text(browser: bool) -> String {
    guide(browser)
        .into_iter()
        .flat_map(|(_, paragraphs)| paragraphs)
        .collect::<Vec<_>>()
        .join(" ")
}

/// The brand mark: a lens with a runtime pulse leaving it, on a dark tile.
pub(crate) fn mark(size: Pixels) -> Div {
    let inner = size * 0.82;
    let inset = (size - inner) / 2.;
    let layer = |path: &'static str, color: u32| {
        svg()
            .path(path)
            .absolute()
            .top(inset)
            .left(inset)
            .size(inner)
            .text_color(rgb(color))
    };
    div()
        .size(size)
        .flex_shrink_0()
        .relative()
        .rounded(size * 0.23)
        .bg(rgb(MARK_BG))
        .child(layer(MARK_LAYERS[0].0, MARK_LENS))
        .child(layer(MARK_LAYERS[1].0, MARK_PULSE))
}

/// The Zano Systems logo tile, decoded once.
fn zano_logo(size: Pixels) -> Img {
    static LOGO: LazyLock<Arc<Image>> =
        LazyLock::new(|| Arc::new(Image::from_bytes(ImageFormat::Png, ZANO_LOGO_PNG.to_vec())));
    img(LOGO.clone())
        .size(size)
        .flex_shrink_0()
        .rounded(size * 0.23)
}

/// Sidebar attribution, outside the scrolling navigation and session panel.
pub(crate) fn sidebar_backing(
    collapsed: bool,
    focus: &FocusHandle,
    bounds: Rc<Cell<Bounds<Pixels>>>,
) -> AnyElement {
    let focus = focus.clone();
    div()
        .id("sidebar-backing")
        .debug_selector(|| "sidebar-backing".into())
        .track_focus(&focus)
        .tab_stop(true)
        .role(Role::Link)
        .aria_label("Zano company website")
        .w_full()
        .relative()
        .flex()
        .flex_shrink_0()
        .items_center()
        .gap_2()
        .py_2()
        .text_xs()
        .text_color(rgb(MUTED))
        .when(collapsed, |el| {
            el.justify_center()
                .rounded_sm()
                .border_1()
                .border_color(rgba(0))
        })
        .when(!collapsed, |el| {
            el.px_4().border_b_1().border_color(rgb(BORDER))
        })
        .cursor_pointer()
        .hover(|style| style.bg(rgb(CARD)))
        .focus_visible(|style| style.border_color(rgb(super::PURPLE)))
        .on_mouse_down(MouseButton::Left, move |_, window, cx| {
            focus.focus(window, cx)
        })
        .on_click(|_, _, cx| cx.open_url(ZANO_WEBSITE))
        .on_key_down(|event, window, cx| {
            if matches!(event.keystroke.key.as_str(), "enter" | "space") {
                window.prevent_default();
                cx.stop_propagation();
                cx.open_url(ZANO_WEBSITE);
            }
        })
        .tooltip(|window, cx| {
            Tooltip::new(format!("Backed by Zano · {ZANO_WEBSITE}")).build(window, cx)
        })
        .child(zano_logo(px(if collapsed { 24. } else { 20. })))
        .when(!collapsed, |el| {
            el.child("Backed by")
                .child(div().text_color(rgb(ZANO_ACCENT)).child("Zano"))
        })
        .child(
            div()
                .absolute()
                .inset_0()
                .child(canvas(move |rect, _, _| bounds.set(rect), |_, _, _, _| {}).size_full()),
        )
        .into_any_element()
}

/// Shared header actions, with native-safe event handling and keyboard focus.
pub(crate) fn header_actions(
    about_bounds: Rc<Cell<Bounds<Pixels>>>,
    help_bounds: Rc<Cell<Bounds<Pixels>>>,
) -> impl IntoElement {
    div()
        .id("header-actions")
        .debug_selector(|| "header-actions".into())
        .flex()
        .flex_shrink_0()
        .items_center()
        .gap_1()
        .pr_2()
        .on_mouse_down(MouseButton::Left, |_, _, cx| cx.stop_propagation())
        .on_click(|_, _, cx| cx.stop_propagation())
        .child(
            div()
                .debug_selector(|| "header-about".into())
                .relative()
                .child(
                    Button::new("header-about")
                        .ghost()
                        .with_size(px(24.))
                        .child(Icon::new(IconName::Info).size(px(14.)))
                        .accessibility_label("About ZView")
                        .tooltip("About ZView")
                        .on_click(|_, window, cx| open_about(window, cx)),
                )
                .child(div().absolute().inset_0().child(
                    canvas(move |rect, _, _| about_bounds.set(rect), |_, _, _, _| {}).size_full(),
                )),
        )
        .child(
            div()
                .debug_selector(|| "header-help".into())
                .relative()
                .child(
                    Button::new("header-help")
                        .ghost()
                        .with_size(px(24.))
                        .child(Icon::new(assets::IconName::Keyboard).size(px(14.)))
                        .accessibility_label("Help & shortcuts")
                        .tooltip("Help & shortcuts")
                        .on_click(|_, window, cx| open_help(window, cx)),
                )
                .child(div().absolute().inset_0().child(
                    canvas(move |rect, _, _| help_bounds.set(rect), |_, _, _, _| {}).size_full(),
                )),
        )
}

fn keycap(key: &'static str) -> Div {
    div()
        .px_1p5()
        .min_w(px(22.))
        .flex()
        .justify_center()
        .rounded_sm()
        .border_1()
        .border_color(rgb(BORDER))
        .bg(rgb(CARD))
        .text_xs()
        .font_family("JetBrains Mono")
        .map(|el| match key {
            RESET_ICON => el
                .py_0p5()
                .child(Icon::new(assets::IconName::RotateCcw).xsmall()),
            FIT_ICON => el.py_0p5().child(Icon::new(IconName::Maximize).xsmall()),
            _ => el.child(key),
        })
}

fn section_title(title: &'static str) -> Div {
    div()
        .text_xs()
        .font_semibold()
        .text_color(rgb(MUTED))
        .child(title.to_uppercase())
}

fn shortcuts() -> Div {
    div()
        .flex()
        .flex_col()
        .gap_4()
        .children(SHORTCUTS.iter().map(|(group, rows)| {
            div()
                .flex()
                .flex_col()
                .gap_1p5()
                .child(section_title(group))
                .children(rows.iter().map(|row| {
                    div()
                        .flex()
                        .items_center()
                        .gap_3()
                        .child(
                            div()
                                .w(px(130.))
                                .flex_shrink_0()
                                .flex()
                                .gap_1()
                                .children(row.keys.iter().map(|key| keycap(key))),
                        )
                        .child(div().text_sm().child(row.action))
                }))
        }))
}

fn guide_view(browser: bool) -> Div {
    div()
        .flex()
        .flex_col()
        .gap_4()
        .children(guide(browser).into_iter().map(|(title, paragraphs)| {
            div()
                .flex()
                .flex_col()
                .gap_1p5()
                .child(section_title(title))
                .children(
                    paragraphs
                        .into_iter()
                        .map(|text| div().text_sm().child(text)),
                )
        }))
}

/// Opens Help & shortcuts: Shortcuts and Guide tabs.
pub(crate) fn open_help(window: &mut Window, cx: &mut App) {
    let browser = cfg!(target_family = "wasm");
    let tab = Rc::new(Cell::new(0usize));
    window.open_dialog(cx, move |dialog, _, _| {
        let selected = tab.get();
        let tab = tab.clone();
        dialog.title("Help & shortcuts").w(px(620.)).child(
            div()
                .debug_selector(|| "help-dialog-content".into())
                .flex()
                .flex_col()
                .gap_4()
                .child(
                    TabBar::new("help-tabs")
                        .underline()
                        .selected_index(selected)
                        .child(Tab::new().label("Shortcuts"))
                        .child(Tab::new().label("Guide"))
                        .on_click(move |index, window, _| {
                            tab.set(*index);
                            window.refresh();
                        }),
                )
                .child(
                    div()
                        .id("help-body")
                        .max_h(px(540.))
                        .overflow_y_scroll()
                        .pr_2()
                        .map(|el| {
                            if selected == 0 {
                                el.child(shortcuts())
                            } else {
                                el.child(guide_view(browser))
                            }
                        }),
                ),
        )
    });
}

